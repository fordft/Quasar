// The SVG is the wordmark source of truth; native icon sizes come from Tauri.
import { copyFileSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const at = (path) => fileURLToPath(new URL(path, import.meta.url));
const svg = readFileSync(at("../assets/brand/quasar-wordmark.svg"), "utf8");
const box = /viewBox="([^"]+)"/u.exec(svg)?.[1]?.split(/\s+/u).map(Number);
const path = /<path\s+d="([^"]+)"/u.exec(svg)?.[1];
if (!box || box.length !== 4 || box.some((value) => !Number.isFinite(value)) || !path) {
  throw new Error("Quasar wordmark must have one path and a numeric viewBox.");
}
const [x, y, width, height] = box;
writeFileSync(at("../frame/public/quasar-wordmark.svg"), svg);
writeFileSync(
  at("../frame/src/shared/lib/wordmark.ts"),
  `/** Generated by pnpm brand:assets from assets/brand/quasar-wordmark.svg. */
export const WORDMARK = {
  x: ${x},
  y: ${y},
  width: ${width},
  height: ${height},
  scaleX: 1,
  scaleY: 1,
  d: ${JSON.stringify(path)},
} as const;
`,
);
for (const [source, destination] of [
  ["128x128.png", "../frame/public/quasar-icon.png"],
  ["128x128@2x.png", "../frame/public/quasar-icon@2x.png"],
  ["icon.png", "../.github/assets/logo.png"],
]) {
  copyFileSync(at(`../desktop/icons/${source}`), at(destination));
}
